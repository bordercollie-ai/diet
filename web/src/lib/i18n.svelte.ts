function isLanguage(value: string | null): value is Language {
  return value === 'en' || value === 'zh' || value === 'ja'
}

// ponytail: OS locale is only a starting guess (used when the user hasn't picked a
// language yet); it maps by 2-letter prefix, e.g. "zh-Hant-TW" and "ja-JP" both match.
function detectOSLanguage(): Language {
  if (typeof navigator === 'undefined') return 'en'
  const prefix = navigator.language?.slice(0, 2).toLowerCase()
  return isLanguage(prefix) ? prefix : 'en'
}

const storedLanguage = typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : null
let currentLanguage: Language = isLanguage(storedLanguage) ? storedLanguage : detectOSLanguage()
let language: Language = $state(currentLanguage)

export function getLanguage(): Language {
  return currentLanguage
}

export function setLanguage(next: Language) {
  currentLanguage = next
  language = next
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem(STORAGE_KEY, next)
  }
}

export function getLocale(): string {
  return locales[language]
}

export function formatDate(value: string | Date, options: Intl.DateTimeFormatOptions): string {
  const date = value instanceof Date ? value : new Date(value.includes('T') ? value : `${value}T12:00:00`)
  return date.toLocaleDateString(getLocale(), options)
}

// Food names are stored per-source-language (e.g. { en, ja } or { en, ja, zh }),
// not every food has every language; fall back to English, then Japanese
// (the two most commonly present), then whatever name exists.
export function foodName(name: Record<string, string>): string {
  return name[language] ?? name.en ?? name.ja ?? Object.values(name)[0] ?? ''
}

export function t(key: TranslationKey | string): string {
  const translationKey = key as TranslationKey
  return (dict[language] as TranslationMap)[translationKey] ?? en[translationKey] ?? ''
}

export function translate(key: TranslationKey | string, lang: Language = currentLanguage): string {
  const translationKey = key as TranslationKey
  return (dict[lang] as TranslationMap)[translationKey] ?? en[translationKey] ?? ''
}

export type CalorieTone = 'empty' | 'unavailable' | 'under' | 'on-target' | 'over'

export function calorieTone(dayCalories: number, targetCalories: number): CalorieTone {
  if (dayCalories === 0) return 'empty'
  if (targetCalories === 0) return 'unavailable'
  const ratio = dayCalories / targetCalories
  return ratio <= 1 ? 'on-target' : 'over'
}

const ACTIVITY_MULTIPLIERS = {
  bmrOnly: 1,
  sedentary: 1.2,
  light: 1.375,
  moderate: 1.55,
  very: 1.725,
  extra: 1.9,
} as const

export function validateProfile(profile: unknown): asserts profile is Profile {
  if (typeof profile !== 'object' || profile === null) invalid('profile')
  const value = profile as Record<string, unknown>
  if (
    typeof value.age !== 'number' ||
    !Number.isInteger(value.age) ||
    value.age < 1 ||
    value.age > 120 ||
    (value.sex !== 'female' && value.sex !== 'male') ||
    typeof value.heightCm !== 'number' ||
    !Number.isFinite(value.heightCm) ||
    value.heightCm < 50 ||
    value.heightCm > 250 ||
    typeof value.weightKg !== 'number' ||
    !Number.isFinite(value.weightKg) ||
    value.weightKg < 10 ||
    value.weightKg > 500 ||
    typeof value.activity !== 'string' ||
    !(value.activity in ACTIVITY_MULTIPLIERS) ||
    typeof value.targetWeightKg !== 'number' ||
    !Number.isFinite(value.targetWeightKg) ||
    value.targetWeightKg < 10 ||
    value.targetWeightKg > 500 ||
    typeof value.targetDate !== 'string' ||
    !/^\d{4}-\d{2}-\d{2}$/.test(value.targetDate)
  )
    invalid('profile')
}

export function estimateMaintenanceCalories(profile: Profile): number {
  return Math.round(estimateBMR(profile) * ACTIVITY_MULTIPLIERS[profile.activity])
}

export function estimateBMR(profile: Profile): number {
  validateProfile(profile)
  const bmr = 10 * profile.weightKg + 6.25 * profile.heightCm - 5 * profile.age + (profile.sex === 'male' ? 5 : -161)
  return Math.round(bmr)
}

export function estimateTargets(profile: Profile, fromDate = new Date().toISOString().slice(0, 10)): Nutrition {
  const days = (Date.parse(`${profile.targetDate}T00:00:00Z`) - Date.parse(`${fromDate}T00:00:00Z`)) / 86_400_000
  if (!Number.isFinite(days) || days <= 0) invalid('target date')
  const calories = Math.round(
    estimateMaintenanceCalories(profile) + ((profile.targetWeightKg - profile.weightKg) * 7700) / days,
  )
  const protein = Math.round(profile.targetWeightKg * 1.6 * 10) / 10
  const fat = Math.round(((calories * 0.25) / 9) * 10) / 10
  const carbohydrates = Math.round(((calories - protein * 4 - fat * 9) / 4) * 10) / 10
  return { calories, protein, fat, carbohydrates }
}

const LEGACY_TARGET_EFFECTIVE_FROM = '0001-01-01'

function targetPeriodsFor(data: AppData): TargetPeriod[] {
  if (data.targetPeriods?.length) return data.targetPeriods
  if (!data.profile) return []
  try {
    return [{ effectiveFrom: LEGACY_TARGET_EFFECTIVE_FROM, targets: resolveTargets(data.profile, data.targetOverrides) }]
  } catch {
    return []
  }
}

export function targetsForDate(data: AppData, date: string): Nutrition | null {
  return targetPeriodsFor(data)
    .filter((period) => period.effectiveFrom <= date)
    .sort((left, right) => left.effectiveFrom.localeCompare(right.effectiveFrom))
    .at(-1)?.targets ?? null
}

export function exerciseCaloriesForDate(data: AppData, date: string): number {
  return data.exerciseCalories?.[date] ?? 0
}

export function calorieTargetForDate(data: AppData, date: string): number {
  const targets = targetsForDate(data, date)
  return targets ? targets.calories + exerciseCaloriesForDate(data, date) : 0
}

export function setExerciseCalories(data: AppData, date: string, calories: number): AppData {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || !Number.isFinite(calories) || calories < 0) invalid('exercise calories')
  return { ...copy(data), exerciseCalories: { ...data.exerciseCalories, [date]: calories } }
}

export function setTargetPeriod(data: AppData, targets: Nutrition, effectiveFrom: string): AppData {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(effectiveFrom) || !validNutrition(targets)) invalid('target period')
  const targetPeriods = [...targetPeriodsFor(data).filter((period) => period.effectiveFrom !== effectiveFrom), { effectiveFrom, targets: copy(targets) }]
    .sort((left, right) => left.effectiveFrom.localeCompare(right.effectiveFrom))
  return { ...copy(data), targetPeriods }
}

function validateTargetOverrides(overrides: unknown): asserts overrides is TargetOverrides {
  if (typeof overrides !== 'object' || overrides === null) invalid('target overrides')
  for (const [key, value] of Object.entries(overrides)) {
    if (
      !['calories', 'protein', 'fat', 'carbohydrates'].includes(key) ||
      typeof value !== 'number' ||
      !Number.isFinite(value) ||
      value < 0
    )
      invalid('target override')
  }
}

type AchievementStats = {
  hasResolvedTargets: boolean
  recordedMeals: number
  temporaryEntries: number
  activeDays: number
  longestOnTargetRun: number
  maxIdentifiedFoodEntries: number
  uniqueIdentifiedFoods: number
  customFoods: number
}

function toDateStamp(iso: string): number {
  return Date.parse(`${iso}T00:00:00Z`)
}

function longestOnTargetRun(data: AppData): number {
  const dates = [...new Set(data.mealEntries.map((entry) => entry.date))].sort()
  let longest = 0
  let current = 0
  let previousDate = ''
  for (const date of dates) {
    const targetCalories = calorieTargetForDate(data, date)
    if (calorieTone(dailyTotals(data, date).calories, targetCalories) !== 'on-target') {
      current = 0
      previousDate = date
      continue
    }
    current = previousDate && toDateStamp(date) - toDateStamp(previousDate) === 86_400_000 ? current + 1 : 1
    previousDate = date
    longest = Math.max(longest, current)
  }
  return longest
}

function achievementStats(data: AppData, asOfDate: string): AchievementStats {
  const identifiedEntries = data.mealEntries.filter((entry) => entry.foodId !== '')
  const countsByFoodId = identifiedEntries.reduce((counts, entry) => {
    counts.set(entry.foodId, (counts.get(entry.foodId) ?? 0) + 1)
    return counts
  }, new Map<string, number>())
  return {
    hasResolvedTargets: targetsForDate(data, asOfDate) !== null,
    recordedMeals: data.mealEntries.length,
    temporaryEntries: data.mealEntries.filter((entry) => entry.foodId === '').length,
    activeDays: new Set(data.mealEntries.map((entry) => entry.date)).size,
    longestOnTargetRun: longestOnTargetRun(data),
    maxIdentifiedFoodEntries: Math.max(0, ...countsByFoodId.values()),
    uniqueIdentifiedFoods: countsByFoodId.size,
    customFoods: data.foods.filter((food) => food.source === 'user').length,
  }
}


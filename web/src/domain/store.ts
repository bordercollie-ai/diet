function invalid(message: string): never {
  throw new Error(`Invalid data: ${message}`)
}

function validNutrition(value: unknown): value is Nutrition {
  return (
    typeof value === 'object' &&
    value !== null &&
    ['calories', 'protein', 'fat', 'carbohydrates'].every((key) => {
      const number = (value as Record<string, unknown>)[key]
      return typeof number === 'number' && Number.isFinite(number) && number >= 0
    })
  )
}

function validateAchievementRecord(record: unknown): asserts record is AchievementRecord {
  if (typeof record !== 'object' || record === null) invalid('achievement')
  const value = record as Record<string, unknown>
  if (
    typeof value.id !== 'string' ||
    !achievementIds.has(value.id as AchievementId) ||
    typeof value.unlockedAt !== 'string' ||
    !value.unlockedAt ||
    (value.readAt !== undefined && (typeof value.readAt !== 'string' || !value.readAt))
  )
    invalid('achievement')
}

function validateTargetPeriod(period: unknown): asserts period is TargetPeriod {
  if (typeof period !== 'object' || period === null) invalid('target period')
  const value = period as Record<string, unknown>
  if (typeof value.effectiveFrom !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value.effectiveFrom) || !validNutrition(value.targets))
    invalid('target period')
}

export function validateFood(food: unknown): asserts food is Food {
  if (typeof food !== 'object' || food === null) invalid('food')
  const value = food as Record<string, unknown>
  const names = value.name
  if (
    typeof value.id !== 'string' ||
    !value.id ||
    typeof names !== 'object' ||
    names === null ||
    !Object.values(names).some((name) => typeof name === 'string' && name.trim()) ||
    typeof value.serving !== 'string' ||
    !value.serving.trim() ||
    !validNutrition(value.nutrition) ||
    (value.source !== 'bundled' && value.source !== 'user') ||
    (value.description !== undefined && typeof value.description !== 'string') ||
    (value.updatedAt !== undefined && typeof value.updatedAt !== 'string')
  )
    invalid('food')
}

export function validateMealEntry(entry: unknown, foods: Food[]): asserts entry is MealEntry {
  if (typeof entry !== 'object' || entry === null) invalid('meal entry')
  const value = entry as Record<string, unknown>
  if (
    typeof value.id !== 'string' ||
    !value.id ||
    !/^\d{4}-\d{2}-\d{2}$/.test(String(value.date)) ||
    !/^(?:[01]\d|2[0-3]):[0-5]\d$/.test(String(value.time)) ||
    typeof value.foodId !== 'string' ||
    typeof value.quantity !== 'number' ||
    !Number.isFinite(value.quantity) ||
    value.quantity <= 0 ||
    !validNutrition(value.nutrition) ||
    (value.foodId === '' && (typeof value.foodName !== 'string' || !value.foodName.trim()))
  )
    invalid('meal entry')
}

export function validateAppData(data: unknown): asserts data is AppData {
  if (typeof data !== 'object' || data === null) invalid('application data')
  const value = data as Record<string, unknown>
  if (!Array.isArray(value.foods) || !Array.isArray(value.mealEntries)) invalid('application data')
  value.foods.forEach(validateFood)
  value.mealEntries.forEach((entry) => validateMealEntry(entry, value.foods as Food[]))
  if (
    value.exerciseCalories !== undefined &&
    (typeof value.exerciseCalories !== 'object' ||
      value.exerciseCalories === null ||
      Array.isArray(value.exerciseCalories) ||
      !Object.entries(value.exerciseCalories).every(
        ([date, calories]) => /^\d{4}-\d{2}-\d{2}$/.test(date) && typeof calories === 'number' && Number.isFinite(calories) && calories >= 0,
      ))
  )
    invalid('exercise calories')
  if (value.profile !== undefined) validateProfile(value.profile)
  if (value.targetOverrides !== undefined) validateTargetOverrides(value.targetOverrides)
  if (value.targetPeriods !== undefined) {
    if (!Array.isArray(value.targetPeriods)) invalid('target periods')
    value.targetPeriods.forEach(validateTargetPeriod)
    if (new Set(value.targetPeriods.map((period) => (period as TargetPeriod).effectiveFrom)).size !== value.targetPeriods.length)
      invalid('target period')
  }
  if (value.achievements !== undefined) {
    if (!Array.isArray(value.achievements)) invalid('application data')
    value.achievements.forEach(validateAchievementRecord)
    if (new Set(value.achievements.map((record) => (record as AchievementRecord).id)).size !== value.achievements.length)
      invalid('achievement')
  }
  if (
    value.favoriteFoodIds !== undefined &&
    (!Array.isArray(value.favoriteFoodIds) || !value.favoriteFoodIds.every((id) => typeof id === 'string' && id))
  )
    invalid('favorite food ids')
}

export function createFood(input: Omit<Food, 'id'> & { id?: string }): Food {
  const food = { ...input, id: input.id ?? crypto.randomUUID(), updatedAt: input.updatedAt ?? new Date().toISOString() }
  validateFood(food)
  return copy(food)
}

export function scaleNutrition(nutrition: Nutrition, quantity: number): Nutrition {
  if (!Number.isFinite(quantity) || quantity <= 0) invalid('quantity')
  return Object.fromEntries(Object.entries(nutrition).map(([key, value]) => [key, value * quantity])) as Nutrition
}

export const roundForDisplay = (value: number): number => Math.round(value)

// favoriteFoodIds sorts favorites first (stable, so relative order within each
// group — including any name/relevance ordering the caller already applied —
// is preserved).
export function searchFoods(foods: Food[], query: string, favoriteFoodIds?: readonly string[]): Food[] {
  const needle = query.trim().toLocaleLowerCase()
  const matches = !needle
    ? foods
    : foods.filter(
        (food) =>
          Object.values(food.name).some((value) => value.toLocaleLowerCase().includes(needle)) ||
          (food.description ?? '').toLocaleLowerCase().includes(needle),
      )
  if (!favoriteFoodIds?.length) return matches
  const favorites = new Set(favoriteFoodIds)
  return matches.toSorted((a, b) => Number(favorites.has(b.id)) - Number(favorites.has(a.id)))
}

export function toggleFavoriteFood(data: AppData, id: string): AppData {
  if (!data.foods.some((food) => food.id === id)) invalid('food not found')
  const favorites = new Set(data.favoriteFoodIds ?? [])
  favorites.has(id) ? favorites.delete(id) : favorites.add(id)
  return { ...copy(data), favoriteFoodIds: [...favorites] }
}

export function createMealEntry(input: Omit<MealEntry, 'id' | 'nutrition'> & { id?: string }, food: Food): MealEntry {
  const entry = {
    ...input,
    id: input.id ?? crypto.randomUUID(),
    nutrition: scaleNutrition(food.nutrition, input.quantity),
  }
  validateMealEntry(entry, [food])
  return copy(entry)
}

export function createTemporaryMealEntry(
  input: Omit<MealEntry, 'id' | 'foodId' | 'nutrition'> & { id?: string; foodName: string; nutrition: Nutrition },
): MealEntry {
  const entry = {
    ...input,
    id: input.id ?? crypto.randomUUID(),
    foodId: '',
  }
  validateMealEntry(entry, [])
  return copy(entry)
}

export function updateFood(data: AppData, id: string, changes: Partial<Omit<Food, 'id' | 'source'>>): AppData {
  const food = data.foods.find((item) => item.id === id)
  if (!food) invalid('food not found')
  if (food.source === 'bundled') invalid('bundled food is read-only')
  const next = { ...food, ...changes, updatedAt: new Date().toISOString() }
  validateFood(next)
  return { ...copy(data), foods: data.foods.map((item) => (item.id === id ? next : item)) }
}

export function deleteFood(data: AppData, id: string): AppData {
  const food = data.foods.find((item) => item.id === id)
  if (!food) invalid('food not found')
  if (food.source === 'bundled') invalid('bundled food is read-only')
  return { ...copy(data), foods: data.foods.filter((item) => item.id !== id) }
}

export function updateMealEntry(data: AppData, id: string, changes: Partial<Omit<MealEntry, 'id'>>): AppData {
  const entry = data.mealEntries.find((item) => item.id === id)
  if (!entry) invalid('meal entry not found')
  const next = { ...entry, ...changes }
  if (next.foodId === '') {
    validateMealEntry(next, [])
    return { ...copy(data), mealEntries: data.mealEntries.map((item) => (item.id === id ? copy(next) : item)) }
  }
  const food = data.foods.find((item) => item.id === next.foodId)
  if (!food) invalid('food not found')
  const updated = createMealEntry(next, food)
  return { ...copy(data), mealEntries: data.mealEntries.map((item) => (item.id === id ? updated : item)) }
}

export function deleteMealEntry(data: AppData, id: string): AppData {
  if (!data.mealEntries.some((item) => item.id === id)) invalid('meal entry not found')
  return { ...copy(data), mealEntries: data.mealEntries.filter((item) => item.id !== id) }
}

export function dailyTotals(data: AppData, date: string): Nutrition {
  return data.mealEntries
    .filter((entry) => entry.date === date)
    .reduce(
      (total, entry) => ({
        calories: total.calories + entry.nutrition.calories,
        protein: total.protein + entry.nutrition.protein,
        fat: total.fat + entry.nutrition.fat,
        carbohydrates: total.carbohydrates + entry.nutrition.carbohydrates,
      }),
      { calories: 0, protein: 0, fat: 0, carbohydrates: 0 },
    )
}

